#!/usr/bin/env node

import { execFile as execFileCallback } from "node:child_process";
import { createHash } from "node:crypto";
import {
  chmod,
  copyFile,
  mkdir,
  readFile,
  readdir,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFile = promisify(execFileCallback);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(repoRoot, "apps", "desktop", "resources", "ringer");
const lockFileName = "runtime-lock.json";
const trustedDigestSource = path.join(
  repoRoot,
  "apps",
  "desktop",
  "src",
  "backend",
  "RingerRuntimeDigest.generated.ts",
);

// Keep this deliberately small. Ringer is a single-file Python runtime; the
// other files are runtime dependencies, local diagnostics, or required legal
// material. Tests and screenshots remain in the upstream checkout.
export const RINGER_RUNTIME_SOURCE_FILES = Object.freeze([
  ".claude/skills/ringer/SKILL.md",
  "LICENSE.md",
  "NATE-JONES-MEDIA-INTEGRATION-AUTHORIZATION.md",
  "README.md",
  "config.sample.toml",
  "dashboard/dashboard.html",
  "dashboard/ringside.html",
  "docs/MODEL-NOTES.md",
  "docs/workbench-integration.md",
  "engines/mock_worker.py",
  "engines/opencode-sandboxed.sh",
  "hooks/ringer_nudge.py",
  "registry/model-identity.toml",
  "ringer.py",
]);

const WORKBENCH_NOTICE_FILES = Object.freeze([
  ["RINGER_PRODUCT_AUTHORIZATION.md", "NATE_JONES_MEDIA_AUTHORIZATION.md"],
  ["THIRD_PARTY_NOTICES.md", "THIRD_PARTY_NOTICES.md"],
]);

function sha256(contents) {
  return createHash("sha256").update(contents).digest("hex");
}

function aggregateDigest(entries) {
  const canonical = entries
    // File modes are recorded for review and enforced on POSIX, but are not
    // part of the cross-platform content identity: Windows checkouts do not
    // preserve POSIX executable bits.
    .map((entry) => `${entry.path}\0${entry.sha256}\0${entry.bytes}`)
    .join("\n");
  return sha256(Buffer.from(canonical));
}

export function renderTrustedRingerRuntimeDigestSource(contentSha256) {
  return (
    "// Generated by scripts/sync-ringer-runtime.mjs. Do not edit.\n" +
    "// This value is compiled into the signed desktop application.\n" +
    "export const PACKAGED_RINGER_RUNTIME_SHA256 =\n" +
    `  "${contentSha256}" as const;\n`
  );
}

async function verifyTrustedRingerRuntimeDigest(lock) {
  const expected = renderTrustedRingerRuntimeDigestSource(lock.content_sha256);
  const actual = await readFile(trustedDigestSource, "utf8").catch((error) => {
    if (error && typeof error === "object" && error.code === "ENOENT") {
      throw new Error(`Trusted Ringer runtime digest source is missing: ${trustedDigestSource}`);
    }
    throw error;
  });
  if (actual !== expected) {
    throw new Error(
      "Trusted desktop Ringer digest does not match runtime-lock.json; run pnpm run sync:ringer from the reviewed source.",
    );
  }
}

async function writeTrustedRingerRuntimeDigest(lock) {
  await writeFile(
    trustedDigestSource,
    renderTrustedRingerRuntimeDigestSource(lock.content_sha256),
    "utf8",
  );
}

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch (error) {
    if (error && typeof error === "object" && error.code === "ENOENT") return false;
    throw error;
  }
}

async function fileEntry(root, relativePath) {
  const absolutePath = path.join(root, ...relativePath.split("/"));
  const [contents, metadata] = await Promise.all([readFile(absolutePath), stat(absolutePath)]);
  if (!metadata.isFile()) throw new Error(`Expected a file: ${absolutePath}`);
  return {
    path: relativePath,
    sha256: sha256(contents),
    bytes: contents.byteLength,
    mode: (metadata.mode & 0o777).toString(8).padStart(3, "0"),
  };
}

async function copyTrackedFile(sourceRoot, targetRoot, sourcePath, targetPath = sourcePath) {
  const source = path.join(sourceRoot, ...sourcePath.split("/"));
  const target = path.join(targetRoot, ...targetPath.split("/"));
  const metadata = await stat(source).catch((error) => {
    if (error && typeof error === "object" && error.code === "ENOENT") {
      throw new Error(`Required Ringer runtime file is missing: ${source}`);
    }
    throw error;
  });
  if (!metadata.isFile()) throw new Error(`Required Ringer runtime path is not a file: ${source}`);
  await mkdir(path.dirname(target), { recursive: true });
  await copyFile(source, target);
  await chmod(target, metadata.mode & 0o777);
}

async function gitMetadata(sourceRoot) {
  const runGit = async (args) =>
    (
      await execFile("git", ["-C", sourceRoot, ...args], {
        encoding: "utf8",
      })
    ).stdout.trim();

  try {
    const [revision, remote, selectedStatus] = await Promise.all([
      runGit(["rev-parse", "HEAD"]),
      runGit(["config", "--get", "remote.origin.url"]).catch(() => ""),
      runGit(["status", "--porcelain", "--", ...RINGER_RUNTIME_SOURCE_FILES]),
    ]);
    return {
      repository: remote || null,
      revision,
      selected_source_dirty: selectedStatus.length > 0,
      selected_source_status: selectedStatus ? selectedStatus.split("\n") : [],
    };
  } catch {
    return {
      repository: null,
      revision: "unversioned",
      selected_source_dirty: true,
      selected_source_status: ["Source directory is not a readable Git checkout."],
    };
  }
}

async function listFiles(root, prefix = "") {
  const directory = path.join(root, ...prefix.split("/").filter(Boolean));
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listFiles(root, relativePath)));
    else if (entry.isFile()) files.push(relativePath);
    else throw new Error(`Unsupported runtime entry: ${path.join(root, relativePath)}`);
  }
  return files.sort();
}

export async function verifyRingerRuntime(root = destination) {
  const lockPath = path.join(root, lockFileName);
  const lock = JSON.parse(await readFile(lockPath, "utf8"));
  if (lock.schema_version !== 1 || !Array.isArray(lock.files)) {
    throw new Error(`Unsupported Ringer runtime lock: ${lockPath}`);
  }

  const actualPaths = await listFiles(root);
  const expectedPaths = [...lock.files.map((entry) => entry.path), lockFileName].sort();
  if (JSON.stringify(actualPaths) !== JSON.stringify(expectedPaths)) {
    throw new Error("Bundled Ringer runtime file list does not match runtime-lock.json");
  }

  const actualEntries = [];
  for (const expected of lock.files) {
    const actual = await fileEntry(root, expected.path);
    if (
      actual.sha256 !== expected.sha256 ||
      actual.bytes !== expected.bytes ||
      (process.platform !== "win32" && actual.mode !== expected.mode)
    ) {
      throw new Error(`Bundled Ringer runtime file does not match lock: ${expected.path}`);
    }
    actualEntries.push(actual);
  }
  if (aggregateDigest(actualEntries) !== lock.content_sha256) {
    throw new Error("Bundled Ringer runtime aggregate digest does not match lock");
  }
  return lock;
}

export async function syncRingerRuntime(sourceRoot) {
  const source = path.resolve(sourceRoot);
  if (source === destination || destination.startsWith(`${source}${path.sep}`)) {
    throw new Error("Ringer source must be a separate checkout, not the bundle destination");
  }

  const stage = `${destination}.sync-${process.pid}`;
  const backup = `${destination}.backup-${process.pid}`;
  await rm(stage, { recursive: true, force: true });
  await rm(backup, { recursive: true, force: true });
  await mkdir(stage, { recursive: true });

  try {
    for (const relativePath of RINGER_RUNTIME_SOURCE_FILES) {
      await copyTrackedFile(source, stage, relativePath);
    }
    for (const [sourcePath, targetPath] of WORKBENCH_NOTICE_FILES) {
      await copyTrackedFile(repoRoot, stage, sourcePath, targetPath);
    }

    const filePaths = (await listFiles(stage)).sort();
    const files = [];
    for (const relativePath of filePaths) files.push(await fileEntry(stage, relativePath));
    const sourceMetadata = await gitMetadata(source);
    const lock = {
      schema_version: 1,
      product: "Unlock AI Workbench",
      runtime: "Ringer",
      ...sourceMetadata,
      content_sha256: aggregateDigest(files),
      files,
    };
    await writeFile(path.join(stage, lockFileName), `${JSON.stringify(lock, null, 2)}\n`, "utf8");
    await verifyRingerRuntime(stage);

    const hadDestination = await exists(destination);
    if (hadDestination) await rename(destination, backup);
    try {
      await rename(stage, destination);
      await rm(backup, { recursive: true, force: true });
    } catch (error) {
      if (hadDestination && (await exists(backup)) && !(await exists(destination))) {
        await rename(backup, destination);
      }
      throw error;
    }
    await writeTrustedRingerRuntimeDigest(lock);
    return lock;
  } finally {
    await rm(stage, { recursive: true, force: true });
  }
}

function parseArgs(argv) {
  let check = false;
  let source = process.env.UNLOCK_RINGER_SOURCE ?? "";
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      check = true;
      continue;
    }
    if (argument === "--source") {
      source = argv[index + 1] ?? "";
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }
  return { check, source };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  let lock;
  if (options.check) {
    lock = await verifyRingerRuntime();
    await verifyTrustedRingerRuntimeDigest(lock);
  } else {
    lock = await syncRingerRuntime(
      options.source ||
        (() => {
          throw new Error("Pass --source <ringer-checkout> or set UNLOCK_RINGER_SOURCE");
        })(),
    );
  }
  const verb = options.check ? "Verified" : "Synced";
  console.log(
    `${verb} Ringer ${lock.revision} (${lock.content_sha256.slice(0, 12)}) at ${destination}`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
